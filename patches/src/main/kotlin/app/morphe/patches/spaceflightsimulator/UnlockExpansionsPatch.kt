package app.morphe.patches.spaceflightsimulator

import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.resourcePatch
import java.io.File

/**
 * Unlocks the expansion packs, the store and the cheats menu of Spaceflight Simulator.
 *
 * Why a `resourcePatch` and not a `bytecodePatch`: the gate is C# compiled to native code, so it
 * only exists in `global-metadata.dat` and `libil2cpp.so` (zero hits in DEX). Morphe cannot rewrite
 * the IL, but `ResourcePatchContext.get(path)` reaches raw APK entries, so the gates are neutralized
 * by rewriting instruction words in `libil2cpp.so` for every ABI in the APK.
 *
 * The entitlement model (`global-metadata.dat` + `script.json` + disassembly + decompiled C#):
 *   - `LMEMKLJJJOC` is the purchase-manager singleton (`KHHFOAEAONN()` returns it). It holds nine
 *     `Bool_Local` feature flags, 22 per-SKU entries (`NFPAPMNDEML`) and 13 expansion descriptors
 *     (`FNELDDEGCHB`).
 *   - `NFPAPMNDEML` is one SKU: `string KAPLFBGNFOD` (the product id) plus
 *     `Bool_Local MDCFMFJIAGB` = "this SKU is owned".
 *   - `LMEMKLJJJOC.<>c.ECNHDFDEIGP(NFPAPMNDEML sku)` returns `sku.MDCFMFJIAGB.Value` and IS the
 *     ownership predicate the shop consults. It reads the flag straight off the field, so forcing
 *     the shared `Obs<bool>` accessor call sites could not reach it - this method has to be forced.
 *   - The flags are written from the Play/Apple receipt path (`AndroidPurchaseRecovery.Init`, the
 *     `PFPOLEHEJJG` listener proxies). No receipt means everything stays false.
 *
 * Two mechanisms, kept apart on purpose so a regression can be bisected:
 *   1. `WORD_WRITES` replaces a whole method body with `return true` (the ownership predicate, the
 *      part gates, the store's per-expansion predicate and the cheats flag).
 *   2. `CALL_SITE_FORCES` replaces a single `bl Obs<bool>.ALEDKGMCDCB` with `mov w0, #1`, making that
 *      one flag read true. The shared accessor itself must NOT be patched: it is called from 102
 *      sites across 60+ classes, gameplay state included (`DockingPortModule`, `RocketSave`,
 *      `Stats.WRUGAOMIRXADUMAD`). Only the store/UI sites are forced: the cheats panel
 *      (`SFS.World.PMGOLGVYKUNGOOBD`), the expansions screen (`SFS.UI.JQQECHFPZWKMUEHT`), the planets
 *      menu (`IDPXFOVTORFVYNOM`) and the skin buttons (`JDTIIKLUYWPXKAKX`). Rows are generated by
 *      scanning the binary for `bl` instructions targeting the accessor and mapping each hit back to
 *      its owning method - see the `il2cpp-native-gate-patching` skill.
 *
 * Scope - read before promising anything:
 *   - Covers: the per-SKU ownership predicate the shop consults, parts and build allowance, the cheats
 *     menu, the planets menu and the skin buttons, on both ABIs.
 *   - Does NOT cover: Play Billing itself (no receipt is faked, prices and the real purchase flow are
 *     untouched, nothing is granted server-side) nor `GZRGGLAJZJQJYQWD.GetOwnedGridSize` (infinite
 *     build area) which returns a `Vector2` and needs a value patch, not a bool.
 *   - Unverifiable in effect without playing: the bytes are confirmed present in the installed
 *     artifact and the game boots and runs with them, but the in-game unlock was never observed
 *     (device-side verification kept failing on unrelated issues: locked screen, ROM kills at low
 *     battery, taps desynced from the UI). Treat the effect as unproven, not as verified.
 *
 * Offsets are build specific (versionCode 897). Every write asserts the original instruction bytes
 * first - the full length of the replacement - so an unsupported build fails loudly instead of
 * corrupting the library.
 */
private const val ARM64_LIB = "lib/arm64-v8a/libil2cpp.so"
private const val ARMV7_LIB = "lib/armeabi-v7a/libil2cpp.so"

/** `mov w0, #1` + `ret` */
private const val ARM64_RETURN_TRUE = "20008052c0035fd6"

/** `mov r0, #1` + `bx lr` */
private const val ARM32_RETURN_TRUE = "0100a0e31eff2fe1"

/** `mov w0, #1` - constant `true` from a forced call site (same size as the `bl` it replaces) */
private const val ARM64_MOV_W0_1 = "20008052"

/** `mov r0, #1` - ARM mode, same size as the `bl` it replaces */
private const val ARM32_MOV_R0_1 = "0100a0e3"

/** `mov x1, #1` - arm64, forces the initial value of a freshly created Bool_Local to true */
private const val ARM64_MOV_X1_1 = "21008052"

/** `mov r1, #1` - ARM mode, same purpose */
private const val ARM32_MOV_R1_1 = "0110a0e3"

private data class WordWrite(
    val libPath: String,
    val fileOffset: Int,
    val expectedWord: String,
    val replacement: String,
    val symbol: String,
)

// File offset = virtual address minus the LOAD segment delta (0x4000 for the arm64 .so, 0 for the
// armeabi one); the delta was read from the ELF program headers and every word confirmed in the
// disassembly.
private val WORD_WRITES = listOf(
    // The ownership predicate the shop actually consults: bool ECNHDFDEIGP(NFPAPMNDEML sku) returns
    // sku.MDCFMFJIAGB.Value - the per-SKU "owned" flag, read straight off the field and not through
    // the shared accessor, which is why forcing the accessor call sites never reached it.
    WordWrite(ARM64_LIB, 0x17401B4, "fe0f1ef8f44f01a9", ARM64_RETURN_TRUE, "LMEMKLJJJOC.<>c.ECNHDFDEIGP"),
    WordWrite(ARMV7_LIB, 0xC6799C, "30482de948509fe5", ARM32_RETURN_TRUE, "LMEMKLJJJOC.<>c.ECNHDFDEIGP"),
    WordWrite(ARM64_LIB, 0x17AF4AC, "fe0f1ef8f44f01a9", ARM64_RETURN_TRUE, "VSBEDHEHBUOHCHWD.get_IsOwned"),
    WordWrite(ARMV7_LIB, 0xCF13B4, "30482de9d8509fe5", ARM32_RETURN_TRUE, "VSBEDHEHBUOHCHWD.get_IsOwned"),
    WordWrite(ARM64_LIB, 0x16EEA34, "fe5fbda9f65701a9", ARM64_RETURN_TRUE, "GQEZALXKUKZOVQGD.get_IsPremium"),
    WordWrite(ARMV7_LIB, 0xBFFFFC, "f0482de9fc509fe5", ARM32_RETURN_TRUE, "GQEZALXKUKZOVQGD.get_IsPremium"),
    WordWrite(ARM64_LIB, 0x1770C14, "fe57bea9f44f01a9", ARM64_RETURN_TRUE, "EDRDUTMFILKPRGQP.HGOOLGOEKMK"),
    WordWrite(ARMV7_LIB, 0xCA38E0, "f0482de964519fe5", ARM32_RETURN_TRUE, "EDRDUTMFILKPRGQP.HGOOLGOEKMK"),
    WordWrite(ARM64_LIB, 0x183B234, "fe0f1ff8081c40f9", ARM64_RETURN_TRUE, "JRMHWFEIUSAIOARX.get_AllowsCheats"),
    WordWrite(ARMV7_LIB, 0xDA25D4, "10402de91c4090e5", ARM32_RETURN_TRUE, "JRMHWFEIUSAIOARX.get_AllowsCheats"),
