)

// The per-SKU "owned" flag is created as `new Bool_Local(false)` inside the SKU constructor.
// Forcing that initial value to true makes every SKU start out owned, whatever the store reports.
private val ARGUMENT_FORCES = listOf(
    // NFPAPMNDEML..ctor: new Bool_Local(false) -> new Bool_Local(true)
    WordWrite(ARM64_LIB, 0x17D542C, "e1031faa", ARM64_MOV_X1_1, "NFPAPMNDEML..ctor"),
    WordWrite(ARMV7_LIB, 0xD21F5C, "0010a0e3", ARM32_MOV_R1_1, "NFPAPMNDEML..ctor"),
)

// One call to `Obs<bool>.ALEDKGMCDCB` inside store/UI code, replaced with a constant `true`.
private val CALL_SITE_FORCES = listOf<WordWrite>(
    // arm64-v8a - 22 forced call sites in the store/UI code

    // armeabi-v7a - 22 forced call sites in the store/UI code

)

val unlockExpansionsPatch = resourcePatch(
    name = "Unlock expansions",
    description = "Forces the native il2cpp entitlement gates in libil2cpp.so to true (arm64-v8a and armeabi-v7a): the per-SKU ownership predicate the shop consults, part ownership, build allowance, the cheats menu, the planets menu and the skins. No receipt is faked, so Play Billing itself is untouched."
) {
    compatibleWith(Constants.COMPATIBILITY_SFS)

    execute {
        (WORD_WRITES + CALL_SITE_FORCES + ARGUMENT_FORCES).groupBy { it.libPath }.forEach { (libPath, writes) ->
            val lib: File = get(libPath)
            val bytes = lib.readBytes()

            writes.forEach { write ->
                val expected = write.expectedWord.hexToBytes()
                val found = bytes.copyOfRange(write.fileOffset, write.fileOffset + expected.size)
                if (!found.contentEquals(expected)) {
                    throw PatchException(
                        "$libPath @0x${write.fileOffset.toString(16)} (${write.symbol}): " +
                            "expected ${write.expectedWord}, found ${found.toHexString()} - unsupported build"
                    )
                }

                write.replacement.hexToBytes().forEachIndexed { index, byte ->
                    bytes[write.fileOffset + index] = byte
                }
            }

            lib.writeBytes(bytes)
        }
    }
}

private fun String.hexToBytes(): ByteArray =
    chunked(2).map { it.toInt(16).toByte() }.toByteArray()
